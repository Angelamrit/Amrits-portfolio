// Builds the blurred placeholders for the photography that ships with the site.
//
//   node scripts/image-placeholders.mjs
//
// For every photograph under public/images (the exported web copies, not the
// originals in real_pictures/, which the site never serves) this writes a tiny
// 16-pixel-wide WebP of it, as a data URL, into src/data/placeholders.generated.ts.
// The image registry (src/data/images.ts) attaches them to its entries, and
// next/image draws each one, enlarged and blurred, in the frame while the real
// photograph downloads — so a picture never arrives as a pop into an empty box.
// Each is a few hundred bytes; the whole file is a few kilobytes and lives only
// on the server. (A TypeScript module rather than JSON so the test runner, plain
// Node, can import it without a JSON import attribute.)
//
// Run it again after adding or replacing a photograph. Photographs uploaded
// through the dashboard get theirs at upload time (src/lib/content/gallery.ts).
import sharp from "sharp";
import { readdir, readFile, writeFile } from "node:fs/promises";

const ROOT = new URL("../public/images/", import.meta.url);
const OUT = new URL("../src/data/placeholders.generated.ts", import.meta.url);
const GROUPS = ["chef", "food", "restaurant", "placeholders"];
/** Wide enough to keep the composition, small enough to stay a few hundred bytes. */
const WIDTH = 16;

const result = {};
for (const group of GROUPS) {
  const dir = new URL(`${group}/`, ROOT);
  let files;
  try {
    files = await readdir(dir);
  } catch {
    continue;
  }
  for (const file of files.sort()) {
    if (!/\.(jpe?g|png|webp|avif)$/i.test(file)) continue;
    const bytes = await readFile(new URL(file, dir));
    const tiny = await sharp(bytes)
      .rotate()
      .resize({ width: WIDTH, withoutEnlargement: true })
      .webp({ quality: 50, alphaQuality: 50, effort: 6 })
      .toBuffer();
    result[`/images/${group}/${file}`] = `data:image/webp;base64,${tiny.toString("base64")}`;
  }
}

const lines = Object.entries(result).map(([path, url]) => `  ${JSON.stringify(path)}: ${JSON.stringify(url)},`);
await writeFile(
  OUT,
  [
    "// Generated by scripts/image-placeholders.mjs — do not edit by hand; run the script again instead.",
    "// Each entry is a 16-pixel-wide WebP of the photograph at that path, drawn blurred while the real file loads.",
    "export const placeholders: Record<string, string> = {",
    ...lines,
    "};",
    "",
  ].join("\n"),
);
const bytes = Object.values(result).reduce((sum, url) => sum + url.length, 0);
console.log(`${Object.keys(result).length} placeholders, ${(bytes / 1024).toFixed(1)}KB in total`);
